# SAFE ACCESSOR HELPERS
# =========================
def _safe_first_valid(series: pd.Series, default: Any = None) -> Any:
    """Return first non-NaN value or default."""
    if series is None or series.empty:
        return default
    valid = series.dropna()
    return valid.iloc[0] if not valid.empty else default


def _safe_list_from_series(series: pd.Series, max_len: int | None = None) -> list:
    """Convert series to list, dropping NaN, with optional length limit."""
    if series is None or series.empty:
        return []
    vals = series.dropna().tolist()
    return vals[:max_len] if max_len else vals


def _get_last_date_safe(df: pd.DataFrame, date_col: str = "date") -> pd.Timestamp | None:
    """Get max date from dataframe, returning None if empty/invalid."""
    if df is None or df.empty or date_col not in df.columns:
        return None
    dates = pd.to_datetime(df[date_col], errors="coerce").dropna()
    return dates.max() if not dates.empty else None


