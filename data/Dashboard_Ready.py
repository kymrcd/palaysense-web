@st.cache_resource(show_spinner=False)
def _get_dashboard_instance(version_key: tuple) -> DashboardData:
    """Cached singleton instance of DashboardData."""
    return DashboardData()


def reload_dashboard_data() -> DashboardData:
    """
    Main entry point for UI pages.
    Returns a DashboardData object with lazy-loaded Parquet data.
    Cache invalidates when Parquet files change or upload_refresh_key changes.
    """
    version_key = _get_cache_version_key()
    return _get_dashboard_instance(version_key)


