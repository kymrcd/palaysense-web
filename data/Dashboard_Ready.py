# HIGH-LEVEL ACCESSOR CLASS
# =========================
class DashboardData:
    """
    Lightweight container providing attribute-style access to all dashboard data.
    Mimics the old `_DashboardReady` object but loads data on-demand from Parquet.
    All properties are defensive against empty/missing data.
    """
    __slots__ = (
        "_provincial_df", "_supply_df", "_municipality_df",
        "_municipality_history_df", "_municipal_production_df",
        "_forecast_3months_fancy",
        "_forecast_variety_3months", "_forecast_quarterly_yield",
        "_df_municipal_forecasts", "_municipal_results",
        "_model_name_fancy", "_model_name_regular", "_model_name_yield",
        "_mae_fancy", "_rmse_fancy", "_r2_fancy",
        "_mae_regular", "_rmse_regular", "_r2_regular",
        "_mae_yield", "_rmse_yield", "_r2_yield",
        "_loaded",
    )

    def __init__(self):
        self._loaded = False

    def _ensure_loaded(self):
        """Lazy-load all data on first access."""
        if self._loaded:
            return

        # Load historical data
        self._provincial_df = load_provincial_history()
        self._supply_df = load_supply_data()
        self._municipality_df = load_municipal_history()
        self._municipality_history_df = load_municipal_history()
        self._municipal_production_df = load_municipal_production()

        # Load forecasts from provincial_forecasts parquet.
        # Provincial price forecasts are 6 months; yield is 4 quarters.
        forecasts_df = load_provincial_forecasts()
        if (
            not forecasts_df.empty
            and "forecast_type" in forecasts_df.columns
            and "forecast_value" in forecasts_df.columns
        ):
            fancy = _safe_list_from_series(
                forecasts_df[forecasts_df["forecast_type"] == "fancy"]["forecast_value"],
                max_len=6
            )
            regular = _safe_list_from_series(
                forecasts_df[forecasts_df["forecast_type"] == "regular"]["forecast_value"],
                max_len=6
            )
            yield_fc = _safe_list_from_series(
                forecasts_df[forecasts_df["forecast_type"] == "yield"]["forecast_value"],
                max_len=4
            )
            self._forecast_3months_fancy = fancy
            self._forecast_variety_3months = regular
            self._forecast_quarterly_yield = yield_fc
        else:
            self._forecast_3months_fancy = []
            self._forecast_variety_3months = []
            self._forecast_quarterly_yield = []

        # Municipal forecasts (test-period format for UI)
        self._df_municipal_forecasts = load_municipal_forecasts()

        # Metrics with safe defaults
        metrics = load_metrics()
        self._model_name_fancy = metrics.get("fancy", {}).get("model_name", "Unknown")
        self._model_name_regular = metrics.get("regular", {}).get("model_name", "Unknown")
        self._model_name_yield = metrics.get("yield", {}).get("model_name", "Unknown")
        self._mae_fancy = float(metrics.get("fancy", {}).get("mae", 0.0) or 0.0)
        self._rmse_fancy = float(metrics.get("fancy", {}).get("rmse", 0.0) or 0.0)
        self._r2_fancy = float(metrics.get("fancy", {}).get("r2", 0.0) or 0.0)
        self._mae_regular = float(metrics.get("regular", {}).get("mae", 0.0) or 0.0)
        self._rmse_regular = float(metrics.get("regular", {}).get("rmse", 0.0) or 0.0)
        self._r2_regular = float(metrics.get("regular", {}).get("r2", 0.0) or 0.0)
        self._mae_yield = float(metrics.get("yield", {}).get("mae", 0.0) or 0.0)
        self._rmse_yield = float(metrics.get("yield", {}).get("rmse", 0.0) or 0.0)
        self._r2_yield = float(metrics.get("yield", {}).get("r2", 0.0) or 0.0)

        # Municipal results (not loaded by default to save memory)
        self._municipal_results = {}

        self._loaded = True

    # --- Properties for historical data ---
    @property
    def provincial_df(self) -> pd.DataFrame:
        self._ensure_loaded()
        return self._provincial_df

    @property
    def supply_df(self) -> pd.DataFrame:
        self._ensure_loaded()
        return self._supply_df

    @property
    def municipality_df(self) -> pd.DataFrame:
        self._ensure_loaded()
        return self._municipality_df

    @property
    def municipality_history_df(self) -> pd.DataFrame:
        self._ensure_loaded()
        return self._municipality_history_df

    @property
    def municipal_production_df(self) -> pd.DataFrame:
        """Per-municipality palay PRODUCTION volumes (not prices).

        Authoritative source for Top-5 production rankings / seasonal pies.
        """
        self._ensure_loaded()
        return self._municipal_production_df

    # --- Properties for forecasts (always return list, never raise) ---
    @property
    def forecast_3months_fancy(self) -> list:
        self._ensure_loaded()
        return self._forecast_3months_fancy

    @property
    def forecast_variety_3months(self) -> list:
        self._ensure_loaded()
        return self._forecast_variety_3months

    @property
    def forecast_quarterly_yield(self) -> list:
        self._ensure_loaded()
        return self._forecast_quarterly_yield

    @property
    def df_municipal_forecasts(self) -> pd.DataFrame:
        self._ensure_loaded()
        return self._df_municipal_forecasts

    @property
    def municipal_results(self) -> dict:
        self._ensure_loaded()
        return self._municipal_results

    # --- Properties for metrics ---
    @property
    def model_name_fancy(self) -> str:
        self._ensure_loaded()
        return self._model_name_fancy

    @property
    def model_name_regular(self) -> str:
        self._ensure_loaded()
        return self._model_name_regular

    @property
    def model_name_yield(self) -> str:
        self._ensure_loaded()
        return self._model_name_yield

    @property
    def mae_fancy(self) -> float:
        self._ensure_loaded()
        return self._mae_fancy

    @property
    def rmse_fancy(self) -> float:
        self._ensure_loaded()
        return self._rmse_fancy

    @property
    def r2_fancy(self) -> float:
        self._ensure_loaded()
        return self._r2_fancy

    @property
    def mae_regular(self) -> float:
        self._ensure_loaded()
        return self._mae_regular

    @property
    def rmse_regular(self) -> float:
        self._ensure_loaded()
        return self._rmse_regular

    @property
    def r2_regular(self) -> float:
        self._ensure_loaded()
        return self._r2_regular

    @property
    def mae_yield(self) -> float:
        self._ensure_loaded()
        return self._mae_yield

    @property
    def rmse_yield(self) -> float:
        self._ensure_loaded()
        return self._rmse_yield

    @property
    def r2_yield(self) -> float:
        self._ensure_loaded()
        return self._r2_yield

    # --- Model benchmark table (defense-grade evaluation) ---
    @property
    def model_evaluation(self) -> pd.DataFrame:
        """Tidy benchmark: selected model vs Naive / Seasonal Naive baselines.

        Built from the evaluation blocks the pipeline writes to metrics.json
        (test-window baselines + walk-forward rolling-origin results).
        """
        return build_model_evaluation_frame(load_metrics())

    # --- Safe computed properties for UI ---
    @property
    def has_provincial_data(self) -> bool:
        """True if provincial history has any rows."""
        self._ensure_loaded()
        return not self._provincial_df.empty

    @property
    def has_municipal_data(self) -> bool:
        """True if municipal history has any rows."""
        self._ensure_loaded()
        return not self._municipality_history_df.empty

    @property
    def has_forecasts(self) -> bool:
        """True if any forecast data exists."""
        self._ensure_loaded()
        return bool(self._forecast_3months_fancy or self._forecast_variety_3months or self._forecast_quarterly_yield)

    @property
    def latest_provincial_date(self) -> pd.Timestamp | None:
        """Latest date in provincial data, or None if empty."""
        self._ensure_loaded()
        return _get_last_date_safe(self._provincial_df, "date")

    @property
    def latest_municipal_date(self) -> pd.Timestamp | None:
        """Latest date in municipal data, or None if empty."""
        self._ensure_loaded()
        return _get_last_date_safe(self._municipality_history_df, "date")

    # --- Forecast horizon metadata ---
    @property
    def provincial_forecast_months(self) -> int:
        """Provincial price forecasts are strictly 6 months."""
        return 6

    @property
    def municipal_forecast_months(self) -> int:
        """Municipal/LGU forecasts are strictly 3 months."""
        return 3


