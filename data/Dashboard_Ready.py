"""
PalaySense — Lightweight Dashboard Data Loader
==============================================
Reads pre-computed Parquet forecasts and historical data.
NO model training, NO pickle loading, NO heavy computation.
All ML work is done offline via `scripts/run_pipeline.py`.

Defensive design:
- All loaders return empty DataFrames/dicts instead of raising
- Properties guard against empty slices with safe defaults
- Cache invalidation via file mtimes + session upload_refresh_key
"""
