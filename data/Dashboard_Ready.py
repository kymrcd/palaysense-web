# =========================
# CACHE KEY GENERATION
# =========================
def _get_cache_version_key() -> tuple:
    """
    Generate a cache invalidation key based on file modification times.
    The cache invalidates when any Parquet/JSON output file changes.
    """
    files_to_watch = [
        PROVINCIAL_HISTORY,
        MUNICIPAL_HISTORY,
        SUPPLY_DATA,
        PROVINCIAL_FORECASTS,
        MUNICIPAL_FORECASTS,
        MUNICIPAL_FORECASTS_FORWARD,
        METRICS_JSON,
        METADATA_JSON,
    ]

    mtimes = []
    for p in files_to_watch:
        try:
            mtimes.append(p.stat().st_mtime)
        except FileNotFoundError:
            mtimes.append(0)

    # Also include upload_refresh_key from session for manual invalidation
    refresh_key = st.session_state.get("upload_refresh_key", 0)

    return (tuple(mtimes), refresh_key)


# =========================
# SAFE LOADER HELPERS
# =========================
def _safe_read_parquet(path: Path, date_cols: list[str] | None = None) -> pd.DataFrame:
    """Read parquet with graceful fallback to empty DataFrame."""
    if not path.exists():
        return pd.DataFrame()
    try:
        df = pd.read_parquet(path)
        if date_cols:
            for col in date_cols:
                if col in df.columns:
                    df[col] = pd.to_datetime(df[col], errors="coerce")
        return df
    except Exception:
        return pd.DataFrame()


def _safe_read_json(path: Path) -> dict:
    """Read JSON with graceful fallback to empty dict."""
    if not path.exists():
        return {}
    try:
        with open(path, "r") as f:
            return json.load(f)
    except Exception:
        return {}


def _safe_load_pickle(path: Path) -> Any:
    """Load pickle with graceful fallback."""
    if not path.exists():
        return None
    try:
        import joblib
        return joblib.load(path)
    except Exception:
        return None


